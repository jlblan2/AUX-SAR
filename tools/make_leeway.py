"""Build leeway.js from the USCG leeway table (tools/OBJECTPROP.DAT).

OBJECTPROP.DAT is the SAROPS object list compiled by Art Allen (USCG R&D Center)
and published with OpenDrift:
https://raw.githubusercontent.com/OpenDrift/opendrift/master/opendrift/models/OBJECTPROP.DAT
Source report: Allen & Plourde, 1999, Review of Leeway: Field Experiments and
Implementation, USCG CG-D-08-99 (the data behind the IAMSAR leeway tables).

Columns per object: downwind slope [%], offset [cm/s], std dev;
right-of-downwind slope, offset, std dev; left-of-downwind slope, offset, std dev.
Slopes apply to the 10 m wind speed.

Run from the AUX-SAR folder:  python tools/make_leeway.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKIP = ("SEWAGE", "MED-WASTE")  # not SAR search objects

GROUPS = [
    ("PIW", "Person in water"),
    ("LIFE-RAFT", "Life rafts"),
    ("USCG-RESCUE", "Life rafts"),
    ("AVIATION", "Life rafts"),
    ("LIFE-CAPSULE", "Survival craft"),
    ("OVATEK", "Survival craft"),
    ("PERSON-POWERED", "Kayak, surfboard, windsurfer"),
    ("SKIFF", "Power boats"),
    ("SPORT", "Power boats"),
    ("FISHING", "Fishing vessels"),
    ("COASTAL", "Fishing vessels"),
    ("SAILBOAT", "Sailboats"),
]


def group_of(obj_id):
    for prefix, name in GROUPS:
        if obj_id.startswith(prefix):
            return name
    return "Debris and other"


def main():
    lines = (ROOT / "tools" / "OBJECTPROP.DAT").read_text(encoding="latin-1").splitlines()
    objects = []
    i = 0
    while i + 2 < len(lines) and not lines[i].startswith("_") and lines[i].strip():
        obj_id = lines[i].split()[0]
        desc = lines[i + 1].strip()
        nums = [float(x) for x in lines[i + 2].split()]
        i += 3
        if obj_id.startswith(SKIP):
            continue
        level = len(desc) - len(desc.lstrip(">"))
        objects.append({
            "id": obj_id,
            "group": group_of(obj_id),
            "level": level,
            "name": desc.lstrip(">").strip(),
            "dwl": [nums[0], nums[1]],
            "cwlR": [nums[3], nums[4]],
            "cwlL": [nums[6], nums[7]],
        })

    body = ",\n".join("  " + json.dumps(o, separators=(", ", ": ")) for o in objects)
    out = (
        "// Generated by tools/make_leeway.py from the USCG SAROPS leeway table\n"
        "// (Allen & Plourde 1999, CG-D-08-99). Do not edit by hand.\n"
        "// Each pair is [slope %, offset cm/s] against the 10 m wind speed:\n"
        "// dwl = downwind, cwlR = crosswind right of downwind, cwlL = crosswind left.\n"
        f"export const LEEWAY_OBJECTS = [\n{body},\n];\n"
    )
    (ROOT / "leeway.js").write_text(out, encoding="utf-8")
    print(f"{len(objects)} objects written to leeway.js")


if __name__ == "__main__":
    main()
